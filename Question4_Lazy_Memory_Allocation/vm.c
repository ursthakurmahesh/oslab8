// Question 4: Modified copyuvm() for Lazy Allocation
// When forking, parent may have allocated heap space that has not yet been touched.
// In stock xv6, copyuvm calls panic() if a PTE is not present.
// For lazy allocation, copyuvm simply skips unmapped pages!
pde_t*
copyuvm(pde_t *pgdir, uint sz)
{
  pde_t *d;
  pte_t *pte;
  uint pa, i, flags;
  char *mem;

  if((d = setupkvm()) == 0)
    return 0;
  for(i = 0; i < sz; i += PGSIZE){
    if((pte = walkpgdir(pgdir, (void *) i, 0)) == 0)
      continue; // Skip absent page tables
    if(!(*pte & PTE_P))
      continue; // Skip untouched lazily-allocated pages without panicking!
    pa = PTE_ADDR(*pte);
    flags = PTE_FLAGS(*pte);
    if((mem = kalloc()) == 0)
      goto bad;
    memmove(mem, (char*)P2V(pa), PGSIZE);
    if(mappages(d, (void*)i, PGSIZE, V2P(mem), flags) < 0) {
      kfree(mem);
      goto bad;
    }
  }
  return d;

bad:
  freevm(d);
  return 0;
}
